/**
 * Normalizes the potrace-traced monument SVGs in assets/monuments into a single
 * typed module the app can render inline and recolor.
 *
 * The source files are single-colour silhouettes (`fill="#000000"`, `stroke="none"`)
 * wrapped in a flipped `<g transform="translate(0,H) scale(0.1,-0.1)">`. We keep that
 * group intact and only swap the hard-coded fill for `currentColor` so the focus /
 * ghost states can be driven entirely from CSS.
 *
 * Run: node scripts/generate-monument-art.mjs
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const SRC = "assets/monuments";
const OUT = "src/lib/monument-art.ts";

const files = (await readdir(SRC)).filter((f) => f.endsWith(".svg")).sort();

const entries = await Promise.all(
  files.map(async (file) => {
    const slug = file.replace(/\.svg$/, "");
    const raw = await readFile(join(SRC, file), "utf8");

    const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1];
    if (!viewBox) throw new Error(`${file}: no viewBox`);

    const [, , w, h] = viewBox.split(/\s+/).map(Number);

    // Everything between the opening <svg ...> and closing </svg>, minus the
    // potrace metadata block and the XML prolog.
    const body = raw
      .slice(raw.indexOf(">", raw.indexOf("<svg")) + 1, raw.lastIndexOf("</svg>"))
      .replace(/<metadata>[\s\S]*?<\/metadata>/g, "")
      .replace(/fill="#000000"/g, 'fill="currentColor"')
      .replace(/\s+/g, " ")
      .trim();

    if (body.includes("#000000")) throw new Error(`${file}: unconverted black fill`);

    return { slug, viewBox, width: w, height: h, body };
  })
);

const module = `// GENERATED by scripts/generate-monument-art.mjs — do not edit by hand.
// Source: assets/monuments/*.svg

export type MonumentArt = {
  /** Intrinsic viewBox of the traced silhouette. */
  viewBox: string;
  /** Intrinsic aspect ratio (width / height), used to size the skyline slot. */
  aspect: number;
  /** Inline SVG body with \`fill="currentColor"\` so state can drive colour. */
  body: string;
};

export const MONUMENT_ART: Record<string, MonumentArt> = {
${entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.slug)}: {\n` +
      `    viewBox: ${JSON.stringify(e.viewBox)},\n` +
      `    aspect: ${(e.width / e.height).toFixed(4)},\n` +
      `    body: ${JSON.stringify(e.body)},\n` +
      `  },`
  )
  .join("\n")}
};

export type MonumentSlug = keyof typeof MONUMENT_ART;
`;

await writeFile(OUT, module, "utf8");

const total = entries.reduce((n, e) => n + e.body.length, 0);
console.log(`${entries.length} monuments → ${OUT} (${(total / 1024).toFixed(0)} KB of path data)`);
for (const e of entries) {
  console.log(`  ${e.slug.padEnd(30)} ${(e.width / e.height).toFixed(2)}`);
}
